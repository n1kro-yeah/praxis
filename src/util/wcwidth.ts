function inRanges(code: number, ranges: readonly Range[]): boolean {
  let low = 0
  let high = ranges.length - 1
  while (low <= high) {
    const mid = (low + high) >> 1
    const range = ranges[mid] as Range
    if (code < range[0]) high = mid - 1
    else if (code > range[1]) low = mid + 1
    else return true
  }
  return false
}

/** Width of a single code point in terminal cells. */
export function codePointWidth(code: number): number {
  if (code === 0) return 0
  if (code < 32 || (code >= 0x7f && code < 0xa0)) return 0 // control chars
  if (inRanges(code, ZERO_WIDTH)) return 0
  if (inRanges(code, WIDE)) return 2
  return 1
}

const ZWJ = 0x200d
const VS16 = 0xfe0f
const REGIONAL_START = 0x1f1e6
const REGIONAL_END = 0x1f1ff

/**
 * Display width of a string, accounting for emoji ZWJ sequences, regional
 * indicator pairs (flags), variation selectors and skin-tone modifiers.
 */
export function stringWidth(input: string): number {
  if (input === "") return 0
  let width = 0
  let i = 0
  const points: number[] = []
  for (const ch of input) points.push(ch.codePointAt(0) as number)

  while (i < points.length) {
    const code = points[i] as number

    // Regional indicator pairs render as a single double-width flag.
    if (code >= REGIONAL_START && code <= REGIONAL_END) {
      const next = points[i + 1]
      if (next !== undefined && next >= REGIONAL_START && next <= REGIONAL_END) {
        width += 2
        i += 2
        continue
      }
    }

    let cellWidth = codePointWidth(code)
    i++

    // Absorb the rest of the grapheme cluster: variation selectors, combining
    // marks, modifiers, and ZWJ-joined continuations.
    for (;;) {
      const next = points[i]
      if (next === undefined) break
      if (next === VS16) {
        // Emoji presentation promotes the base character to double width.
        if (cellWidth === 1) cellWidth = 2
        i++
        continue
      }
      if (codePointWidth(next) === 0 && next !== ZWJ) {
        i++
        continue
      }
      if (next === ZWJ) {
        i++
        // Consume the joined code point (and its own modifiers on the next pass).
        if (points[i] !== undefined) i++
        continue
      }
      break
    }

    width += cellWidth
  }
  return width
}

/** Splits a string into grapheme-ish clusters suitable for cursor movement. */
export function graphemes(input: string): string[] {
  const out: string[] = []
  const chars = [...input]
  let i = 0
  while (i < chars.length) {
    let cluster = chars[i] as string
    i++
    for (;;) {
      const next = chars[i]
      if (next === undefined) break
      const code = next.codePointAt(0) as number
      if (code === VS16 || code === ZWJ || codePointWidth(code) === 0) {
        cluster += next
        i++
        if (code === ZWJ && chars[i] !== undefined) {
          cluster += chars[i]
          i++
        }
        continue
      }
      if (
        code >= REGIONAL_START &&
        code <= REGIONAL_END &&
        (cluster.codePointAt(0) as number) >= REGIONAL_START &&
        (cluster.codePointAt(0) as number) <= REGIONAL_END &&
        [...cluster].length === 1
      ) {
        cluster += next
        i++
        continue
      }
      break
    }
    out.push(cluster)
  }
  return out
}

/** Truncates to a maximum cell width, appending an ellipsis when clipped. */
export function truncateToWidth(input: string, maxWidth: number, ellipsis = "\u2026"): string {
  if (maxWidth <= 0) return ""
  if (stringWidth(input) <= maxWidth) return input
  const suffixWidth = stringWidth(ellipsis)
  const budget = Math.max(0, maxWidth - suffixWidth)
  let width = 0
  let out = ""
  for (const cluster of graphemes(input)) {
    const w = stringWidth(cluster)
    if (width + w > budget) break
    out += cluster
    width += w
  }
  return out + ellipsis
}

/** Pads a string to an exact cell width. */
export function padToWidth(
  input: string,
  width: number,
  align: "left" | "right" | "center" = "left",
  fill = " ",
): string {
  const current = stringWidth(input)
  if (current >= width) return truncateToWidth(input, width)
  const deficit = width - current
  if (align === "left") return input + fill.repeat(deficit)
  if (align === "right") return fill.repeat(deficit) + input
  const left = Math.floor(deficit / 2)
  return fill.repeat(left) + input + fill.repeat(deficit - left)
}

/** Slices by display columns rather than code units. */
export function sliceByWidth(input: string, start: number, end?: number): string {
  const limit = end ?? Infinity
  let column = 0
  let out = ""
  for (const cluster of graphemes(input)) {
    const w = stringWidth(cluster)
    const next = column + w
    if (next > start && column < limit) out += cluster
    column = next
    if (column >= limit) break
  }
  return out
}
